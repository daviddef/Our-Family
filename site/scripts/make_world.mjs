// Draws the land of the world as seen from Brisbane (azimuthal equidistant, Brisbane at the centre) into
// src/data/world.js. Run it once, from a scratch folder that has the three packages (they are NOT dependencies of
// this site; the page ships only the finished path):
//   mkdir /tmp/mapgen && cd /tmp/mapgen && npm init -y && npm i world-atlas@2.0.2 topojson-client@3.1.0 d3-geo@3.1.1
//   node <this file's path> /tmp/mapgen   (the argument is the scratch folder)
// Land is Natural Earth 1:110m (public domain), through the world-atlas package.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
const dir = process.argv[2];
const req = createRequire(join(dir, "package.json"));
const { geoAzimuthalEquidistant, geoPath } = req("d3-geo");
const { feature } = req("topojson-client");
const topo = req("world-atlas/land-110m.json");
const R = 300;                                       // the far side of the Earth is this many units from the centre
const proj = geoAzimuthalEquidistant().rotate([-153.0251, 27.4698]).scale(R / Math.PI).translate([0, 0]).clipAngle(179.9).precision(0.3);
const d = geoPath(proj).digits(1)(feature(topo, topo.objects.land));
const out = `// GENERATED by scripts/make_world.mjs. The land of the world as seen from Brisbane: Natural Earth 1:110m, azimuthal
// equidistant, Brisbane at (0, 0), the far side of the Earth ${R} units away. Do not edit by hand.
export const WORLD_R = ${R};
export const WORLD_LAND = ${JSON.stringify(d)};
`;
writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "../src/data/world.js"), out);
console.log("land path:", d.length, "characters");
